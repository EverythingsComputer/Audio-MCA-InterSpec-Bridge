"""Spectrum file writers: atomic, InterSpec-compatible output.

Writes .spe (Ortec ASCII), .spc (binary) and .n42 (N42 2012 XML) via Sandia's
official SpecUtils python bindings when available; falls back to a built-in
.spe ASCII writer otherwise (still fully InterSpec-readable).

Files are replaced atomically (write temp + os.replace) so InterSpec never
sees a half-written spectrum. Note SpecUtils' own writer refuses to overwrite,
so we always write to a temp path and move it into place.
"""

from __future__ import annotations

import datetime
import os
import tempfile

import numpy as np

try:
    import SpecUtils as _su
    HAVE_SPECUTILS = True
except ImportError:  # pragma: no cover
    HAVE_SPECUTILS = False


def write_spe_ascii(path: str, counts: np.ndarray, live_time: float, real_time: float,
                    title: str = "GS-Bridge live", start_time: datetime.datetime | None = None,
                    detector: str = "GS-PRO-V5", uuid: str | None = None) -> None:
    """Ortec-style SpEC ASCII (.spe) - the most universally accepted format."""
    st = (start_time or datetime.datetime.now()).replace(microsecond=0)
    n = len(counts)
    lines = [
        f"SpectrumName          : {title}",
        "XUnit                 : keV",
        "YUnit                 : ",
        f"Length                : {n}",
        "SubSpcNum             : 1",
        "StartSubSpc           : 0",
        "StopSubSpc            : 0",
        "Comment               : generated by gsbridge (github)",
        f"Realtime              : {real_time:.3f}",
        f"Livetime              : {live_time:.3f}",
        f"Deadtime              : {(real_time - live_time) / real_time * 100.0 if real_time > 0 else 0.0:.3f}",
        f"Date                  : {st.strftime('%m/%d/%Y %H:%M:%S')}",
        f"DataMode              : MCA",
        f"Analyzer              : {detector}",
        "FirstChannel          : 1",
        "McaCalib0             : 0.0",
        "McaCalib1             : 1.0",
        "McaCalib2             : 0.0",
    ]
    if uuid:
        lines.append(f"UUID                  : {uuid}")
    lines += [
        "$SPEC_ID:", title,

        f"$DATE_COMPILED: {st.isoformat()}",
        f"$DATE_MEAS: {st.isoformat()}",
        f"$LIVETIME: {live_time:.3f}",
        f"$REALTIME: {real_time:.3f}",
        "$DATA:",
    ]
    lines += [str(int(c)) for c in counts]
    _atomic_write_text(path, "\n".join(lines) + "\n")


def write_via_specutils(path: str, counts: np.ndarray, live_time: float, real_time: float,
                        fmt: str = "spc", title: str = "GS-Bridge live",
                        start_time: datetime.datetime | None = None,
                        detector: str = "GS-PRO-V5",
                        manufacturer: str = "Bee Research",
                        model: str = "GS-PRO-V5",
                        uuid: str | None = None) -> None:
    """Write using Sandia SpecUtils bindings (fmt: 'spc', 'n42', 'pcf', 'spe')."""
    if not HAVE_SPECUTILS:
        raise RuntimeError("SpecUtils python bindings not installed")
    st = (start_time or datetime.datetime.now()).replace(microsecond=0)

    m = _su.Measurement.new()
    m.setSampleNumber(1)
    m.setTitle(title)
    m.setStartTime(st)
    m.setGammaCounts([int(c) for c in counts], float(live_time), float(real_time))
    m.setDetectorName(detector)

    sf = _su.SpecFile()
    sf.addMeasurement(m, True)
    if uuid:
        try:
            sf.setUuid(uuid)
        except Exception:
            pass

    try:
        sf.setInstrumentManufacturer(manufacturer)
        sf.setInstrumentModel(model)
        sf.setInstrumentType("Audio MCA")
    except Exception:
        pass

    fmt_map = {"spc": _su.SaveSpectrumAsType.SpcBinaryInt,
               "n42": _su.SaveSpectrumAsType.N42_2012,
               "pcf": _su.SaveSpectrumAsType.Pcf,
               "spe": _su.SaveSpectrumAsType.SpcAscii}
    out_fmt = fmt_map[fmt]

    # SpecUtils refuses to overwrite: write to temp then atomic replace
    fd, tmp = tempfile.mkstemp(suffix=f".{fmt}", dir=os.path.dirname(os.path.abspath(path)) or ".")
    os.close(fd)
    os.unlink(tmp)  # writeToFile wants a non-existing path
    try:
        sf.writeToFile(tmp, [1], [detector], out_fmt)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def _atomic_write_text(path: str, text: str) -> None:
    d = os.path.dirname(os.path.abspath(path)) or "."
    fd, tmp = tempfile.mkstemp(suffix=".tmp", dir=d)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def write_spectrum(path: str, counts: np.ndarray, live_time: float, real_time: float, **kw) -> None:
    """Best-effort writer chosen by extension (.spe/.spc/.n42/.pcf)."""
    ext = os.path.splitext(path)[1].lower().lstrip(".")
    if ext in ("spc", "n42", "pcf") and HAVE_SPECUTILS:
        write_via_specutils(path, counts, live_time, real_time, fmt=ext, **kw)
    else:
        write_spe_ascii(path, counts, live_time, real_time, **kw)
